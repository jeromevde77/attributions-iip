/* Banc d'essai de l'évaluation du personnel : aveugle, circuit, synthèse sans moyenne, chiffrement. node test/evaluations.mjs */
import fs from 'node:fs'; import path from 'node:path'; import os from 'node:os';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lucie-eval-'));
process.env.DB_PATH = path.join(dir, 'test.db');
const { default: db } = await import('../src/db/index.js');
db.exec(`CREATE TABLE IF NOT EXISTS utilisateur (id INTEGER PRIMARY KEY, nom_complet TEXT, email TEXT, role TEXT, actif INTEGER DEFAULT 1, mfa_actif INTEGER DEFAULT 0, totp_secret_chiffre TEXT, totp_dernier_pas INTEGER);
  CREATE TABLE IF NOT EXISTS lucie_config (cle TEXT PRIMARY KEY, valeur TEXT);
  CREATE TABLE IF NOT EXISTS lucie_notification (id INTEGER PRIMARY KEY AUTOINCREMENT, type TEXT, titre TEXT, corps TEXT, lien TEXT, cible_role TEXT, cible_user_id INTEGER, cree_par TEXT, cree_le TEXT, lue_par TEXT);`);
db.prepare("INSERT OR IGNORE INTO utilisateur (id, nom_complet, email, role) VALUES (1,'SOHET Charles','d@x','admin'),(2,'DUPONT Anne','a@x','directeur_adjoint'),(3,'TIERS Paul','p@x','secretariat')").run();
const E = await import('../src/lib/evaluationPersonnel.js');
E.migrerEvaluations();
let ok = 0, ko = 0;
const t = (nom, c, d = '') => { if (c) { ok++; console.log('  ok   ' + nom); } else { ko++; console.log('  FAUX ' + nom + (d ? '  → ' + JSON.stringify(d) : '')); } };
const tente = f => { try { f(); return null; } catch (e) { return e; } };
const dir_ = { id: 1, role: 'admin', nom: 'SOHET Charles' }, da = { id: 2, role: 'directeur_adjoint' }, tiers = { id: 3, role: 'secretariat' };
const ref = db.prepare("SELECT id FROM eval_referentiel WHERE fonction='direction_adjointe'").get();
t('référentiel de la direction adjointe posé', !!ref);
t('la direction adjointe ne crée pas', !!tente(() => E.creer({ evalue_user_id: 3, evaluateur_user_id: 2, referentiel_id: ref.id, periode: '2026' }, da)));
const { id } = E.creer({ evalue_user_id: 2, evaluateur_user_id: 1, referentiel_id: ref.id, periode: '2026', objectifs: [{ libelle: 'Piloter la rentrée' }] }, dir_);
const ev = () => E.ligne(id);
t('un tiers n’a aucun rôle', E.roleSur(ev(), tiers) === null);
t('le tiers ne la liste pas', E.mesEvaluations(tiers).length === 0);
t('l’évaluée la liste', E.mesEvaluations(da).length === 1);
E.ouvrir(ev(), dir_);
E.enregistrerGrille(ev(), da, { m1: { v: 3, t: 'secret auto' }, m2: { v: 'NO' }, 'o:ob1': { v: 2 }, c1: { v: 4 }, t1: { v: 2, f: true } });
E.enregistrerGrille(ev(), dir_, { m1: { v: 1, t: 'texte direction' }, m2: { v: 2 }, 'o:ob1': { v: 3 }, c1: { v: 4 }, t1: { v: 2 } });
const brut = db.prepare('SELECT contenu FROM eval_reponse WHERE partie = ?').get('auto').contenu;
t('texte illisible en base', !brut.includes('secret auto') && brut.startsWith('e1.'));
t('aveugle : l’évaluée ne voit pas la grille de la direction', E.lireEvaluation(ev(), da).parties.evaluateur.contenu === null);
t('aveugle : la direction ne voit pas l’auto-évaluation', E.lireEvaluation(ev(), dir_).parties.auto.contenu === null);
t('elle voit la sienne', E.lireEvaluation(ev(), da).parties.auto.contenu?.m1?.v === 3);
t('pas de synthèse avant les deux soumissions', E.lireEvaluation(ev(), da).synthese === null);
t('soumission → attente', E.soumettre(ev(), da) === 'attente');
t('grille soumise : verrouillée', !!tente(() => E.enregistrerGrille(ev(), da, {})));
t('toujours aveugle en attente', E.lireEvaluation(ev(), da).parties.evaluateur.contenu === null);
t('seconde soumission → synthèse', E.soumettre(ev(), dir_) === 'synthese');
const s = E.lireEvaluation(ev(), da).synthese;
const L = idc => s.lignes.find(l => l.id === idc);
t('écart de 2 : divergent', L('m1').classe === 'divergent' && L('m1').ecart === 2);
t('NO d’un côté : à clarifier', L('m2').classe === 'clarifier');
t('écart de 1 : proche', L('o:ob1').classe === 'proche');
t('écart 0 : concordant', L('c1').classe === 'concordant');
t('priorité : divergent et à clarifier', s.priorite.includes('m1') && s.priorite.includes('m2') && !s.priorite.includes('c1'));
t('aucune moyenne dans la synthèse', !JSON.stringify(s).match(/moyenne|globale/i));
t('le compte rendu attend l’entretien', !!tente(() => E.enregistrerCompteRendu(ev(), dir_, {})));
t('l’évaluée ne pose pas l’entretien', !!tente(() => E.poserEntretien(ev(), da, '2026-12-01')));
E.poserEntretien(ev(), dir_, '2026-12-01');
E.enregistrerCompteRendu(ev(), dir_, { points_forts: 'Rigueur', points_developpement: 'Déléguer', plan: [{ axe: 'Déléguer deux dossiers', moyens: 'Point mensuel', echeance: '2027-03' }] });
t('l’évaluée n’écrit pas avant la validation de l’évaluateur', !!tente(() => E.enregistrerCompteRendu(ev(), da, { observations: 'x' })));
t('l’évaluée ne valide pas la première', !!tente(() => E.valider(ev(), da)));
E.valider(ev(), dir_);
t('compte rendu figé pour l’évaluateur', !!tente(() => E.enregistrerCompteRendu(ev(), dir_, { points_forts: 'y' })));
E.enregistrerCompteRendu(ev(), da, { observations: 'Je ne partage pas le point 1.', desaccord: true });
E.valider(ev(), da);
t('validée, avec référence', ev().etat === 'validee' && /^EVAL-2026-/.test(ev().reference));
t('désaccord gardé', E.lireEvaluation(ev(), dir_).compte_rendu.desaccord === true);
t('le journal ne se modifie pas', !!tente(() => db.prepare('DELETE FROM eval_journal').run()) || db.prepare('SELECT COUNT(*) n FROM eval_journal').get().n === 0);
E.journaliser({ user: dir_ }, id, 'essai');
t('le journal ne s’efface pas', !!tente(() => db.prepare('DELETE FROM eval_journal').run()));
console.log(`\n${ok} ok, ${ko} faux`); process.exit(ko ? 1 : 0);
